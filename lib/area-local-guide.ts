export function buildLocalGuide(area: Area) {
  const local = AREA_LOCAL[area.slug];
  const items: LocalGuideItem[] = local
    ? [{ term: `${area.shortName}からのご依頼`, description: local.access }, ...SHARED_ITEMS]
    : SHARED_ITEMS;

  return {
    heading: `${area.shortName}で葬儀場・火葬場をお探しの方へ ― 費用と場所の基本情報`,
    lead: "式場と火葬場の場所、火葬料金の目安、対応している葬儀の形式など、ご葬儀を行う際にまず知っておきたい情報をまとめました。",
    items,
    paragraphs: local
      ? [local.intro, ...SHARED_PARAGRAPHS]
      : SHARED_PARAGRAPHS,
    note: NOTE,
  };
}
