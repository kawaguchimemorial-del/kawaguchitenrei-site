export type VoiceTag = { label: string; matches: string[] };

/**
 * お客様の声を「気になる言葉」で絞り込むタグ。
 * matches のいずれかが title+comment に含まれれば該当（同義語をまとめる）。
 * 担当者名など個人名はタグにしない（§12）。マッチ0件のタグは表示側で自動的に出さない。
 */
